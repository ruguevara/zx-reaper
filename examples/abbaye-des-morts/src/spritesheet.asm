; The sprites that the masked sprite routines draw (QueueSprite, DrawSpriteJob)
; live in one table of 40 pages of 256 bytes ($D700-$FEFF): the byte of pixel
; row r and column c is at $D700 + 256 * r + c, so a sprite is a rectangle of
