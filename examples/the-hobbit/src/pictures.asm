;
; The picture is drawn at $7FA7 from a stream of commands (see Picture01):
; header (border, attribute), then $08 x y = move, $80-$FF = line, $40-$7F =
; fill, $20-$27 = attribute paint, $00 = end. The picture area is the top 128
; pixel rows (16 cell rows); y counts up from the bottom, row = $7F - y.
;
; Picture ids are location numbers: $965B (called from $9630 with A = location)
; draws the picture of the location, if $B707 is non-zero ($6C7C: zero when N
; is held at start-up) and the picture is not suppressed by $95ED (carry set:
; the player cannot see, the screen is left black).
